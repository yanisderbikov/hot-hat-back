-- Приглашение в комнату становится обычным сообщением переписки.
--
-- ─────────────────── Что здесь происходит ───────────────────
-- V11 сразу завела у сообщения колонку room_invite_id и вид 'room_invite':
-- приглашение — это карточка в диалоге, а не отдельная сущность рядом с ним.
-- Писать её было некому: приглашения заводил старый движок портала и клал их
-- вместе с сообщением в таблицы прежнего поколения. Теперь их заводит область
-- комнаты, а карточку в переписке пишет область переписки — и колонка
-- наконец заполняется.
--
-- ─────────────────── Почему трогается только мост ───────────────────
-- room_invite_id объявлен как UUID, а идентификатор приглашения сегодня —
-- строка «ri-<hex10>» (SocialServiceImpl). Тот же тупик, что у игрока и у
-- записи игры, и решается он тем же мостом: прямой перевод считается из самой
-- строки, обратный лежит здесь. Третий вид уже добавляла V16 ради обоймы
-- мемов — этот четвёртый и, судя по плану, предпоследний: мост уйдёт целиком,
-- когда переедут auth и recording.
ALTER TABLE v2.legacy_id_bridge DROP CONSTRAINT ck_legacy_id_bridge_kind;
ALTER TABLE v2.legacy_id_bridge
    ADD CONSTRAINT ck_legacy_id_bridge_kind
    CHECK (kind IN ('player', 'recording', 'meme', 'room_invite'));

-- Приглашения, выданные до переезда. Прямое чтение (id → uuid) в базу не
-- ходит, поэтому пропуск строки писать не мешает; он мешал бы читать —
-- карточка в истории осталась бы без ссылки на комнату.
INSERT INTO v2.legacy_id_bridge (v2_id, kind, legacy_id)
SELECT md5('room_invite:' || id)::uuid, 'room_invite', id
FROM room_invite
ON CONFLICT DO NOTHING;
