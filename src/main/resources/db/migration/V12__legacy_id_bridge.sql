-- Мост между строковым uid старой схемы и uuid новой.
--
-- ─────────────────── Зачем он вообще нужен ───────────────────
-- V11 объявила игрока как UUID: §6.1 плана разрешает это расхождение в пользу
-- uuid, потому что база пересобирается целиком. Но переезжает она по областям,
-- и области auth в новой схеме ещё нет: личность по-прежнему выдаёт
-- AuthServiceImpl.newUid(), то есть 28 символов base62. Пока это так, ни одна
-- таблица кластера v2 не может быть заполнена, а области friends и chat уже
-- обязаны в них писать.
--
-- Значение uuid считается из uid детерминированно — md5('player:' || uid) —
-- поэтому «какой uuid у этого игрока» знает и Java, и SQL, и согласовывать
-- их нечем. Обратный вопрос («чей это uuid») md5 не отвечает, а ответ нужен
-- каждому чтению: в ответах v2 стоит uid, его ждёт фронтенд. Ради него и
-- заведена строка.
--
-- ─────────────────── Почему одна таблица на два вида ───────────────────
-- Тот же тупик у поделённой записи игры: v2.direct_chat_message.shared_recording_id
-- объявлен uuid, а сегодняшний идентификатор записи — «hat-<hex16>-<номер>»
-- (RecordingServiceImpl.recordingId). Вид назван колонкой, а не второй
-- таблицей: обе умрут в один день — когда переедут auth и recording, — и
-- одна строка DROP TABLE лучше двух.
--
-- Таблица временная по замыслу. Её единственный признак жизни — то, что
-- области v2 ещё соседствуют с легаси; когда соседство кончится, она уйдёт
-- вместе с последним строковым uid.
CREATE TABLE v2.legacy_id_bridge (
    v2_id     UUID         NOT NULL,
    kind      VARCHAR(16)  NOT NULL,
    -- 180 — длина идентификатора записи игры (game_recording.id); uid короче.
    legacy_id VARCHAR(180) NOT NULL,
    CONSTRAINT pk_legacy_id_bridge PRIMARY KEY (v2_id),
    CONSTRAINT ck_legacy_id_bridge_kind CHECK (kind IN ('player', 'recording')),
    -- Обратная сторона моста: по старому идентификатору строка тоже одна.
    -- Индекс заодно ловит столкновение md5, если оно вдруг случится: вставка
    -- упадёт, а не подменит игрока молча.
    CONSTRAINT ux_legacy_id_bridge_legacy UNIQUE (kind, legacy_id)
);

-- Игроки, заведённые до переезда. Дальше строки добавляют сами области —
-- на каждой записи, где uid впервые попадает в таблицы v2. Прямое чтение
-- (uid → uuid) в базу не ходит вовсе, поэтому пропуск строки здесь не мешает
-- писать; он мешал бы только читать, и ровно от этого страхует наполнение.
INSERT INTO v2.legacy_id_bridge (v2_id, kind, legacy_id)
SELECT md5('player:' || uid)::uuid, 'player', uid
FROM app_user
ON CONFLICT DO NOTHING;
