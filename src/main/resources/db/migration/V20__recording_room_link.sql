-- Переключение области записей на таблицы схемы v2.
--
-- V17 завела девять таблиц кластера записей и не тронула ни одного сценария:
-- «у записей партий фронта на v2 нет, поэтому таблицы записей остаются
-- пустыми до своего шага». Этот файл — тот самый шаг: сценарии записи
-- (старт, остановка, вебхук Egress, сигналы рекордера, библиотека, уборка)
-- переехали на v2.recording и её соседей.
--
-- Данные НЕ переносятся, и это решение, а не упущение. §11 плана: v2 —
-- отдельный деплой со своей базой, учётки заводятся заново. Переносить в
-- новую базу записи партий, сыгранных чужими учётками в старой, значило бы
-- показать игроку чужую библиотеку: recording_save.player_id ссылается на
-- v2.user_account, а этих строк там нет. Старые записи остаются в
-- game_recording вместе со старым деплоем, который по §11 живёт ещё две
-- недели после переключения.


-- ─────────────── связь записи с комнатой ───────────────
--
-- v2.recording.room_id объявлен внешним ключом на v2.room. Кластер комнаты
-- заведён (V15), но НЕ переключён: писателя у v2.room сегодня нет ни одного —
-- комната по-прежнему живёт в таблице room, и строки в v2.room не появляются
-- ни от миграции, ни от кода. Внешний ключ на пустую таблицу означает, что
-- ни одна запись партии не заведётся вовсе: вставка упадёт на комнате,
-- которой в v2 нет.
--
-- Ключ снимается ровно до переезда комнаты. Колонка, её тип, уникальный ключ
-- идемпотентности ux_recording_game и правило ON DELETE SET NULL, ради
-- которого ключ и был, — всё остаётся описанным в V17 и вернётся вместе с
-- переключением кластера комнаты одним ALTER TABLE ... ADD CONSTRAINT.
--
-- Почему не наоборот — не отложить переезд записей до переезда комнаты.
-- Потому что тогда пришлось бы оставить на game_recording пять жизненных
-- циклов в одной строке ещё на один шаг, а это ровно та беда, ради которой
-- кластер разрезан: вебхук LiveKit переписывал заодно счётчик сохранений, а
-- сохранение записи — состояние Egress. Ждать с этим дороже, чем побыть без
-- одного внешнего ключа.
ALTER TABLE v2.recording DROP CONSTRAINT IF EXISTS recording_room_id_fkey;

COMMENT ON COLUMN v2.recording.room_id IS
    'Комната партии. Внешний ключ на v2.room снят до переезда кластера комнаты (V20): '
    'сегодня в v2.room нет ни одной строки, и ключ запрещал бы заводить записи вовсе.';


-- ─────────────── зачем не тронут room_recording_policy ───────────────
--
-- У таблицы «включена ли запись в комнате» тот же внешний ключ на v2.room и
-- та же беда, но её никто не пишет и не читает: флаг record_game ставит адрес
-- области комнаты, и пока писатель там, область записей читает флаг оттуда же
-- через порт снимка комнаты. Снимать ключ у таблицы, в которую никто не
-- вставляет, значило бы прятать несделанную работу за успешной миграцией.
