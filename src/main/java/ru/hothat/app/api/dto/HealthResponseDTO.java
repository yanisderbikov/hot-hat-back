package ru.hothat.app.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Проба живости: сервис поднят и обрабатывает запросы.
 *
 * <p>Из ответа убран блок {@code env} старого {@code GET /api/health}. Он
 * перечислял анонимному вызывающему десять ключей вида
 * {@code JWT_SECRET: true} — то есть карту того, какие секреты настроены, а
 * какие нет. Знать это снаружи незачем, а подсказка «на этом стенде подпись
 * токенов не настроена» стоит дорого.
 *
 * <p>Версии JVM здесь тоже нет, и это решение, а не забывчивость: её никто не
 * читал, зато она называет анонимному вызывающему набор уязвимостей, которые
 * имеет смысл пробовать.
 *
 * <p>Зависимости — база, хранилище, LiveKit — намеренно не проверяются:
 * это проба живости, а не готовности. Балансировщик по ней решает, жив ли
 * процесс; состояние интеграций показывает агент мониторинга, у которого
 * своя поверхность и свои права.
 */
@Schema(description = "Ответ пробы живости")
public record HealthResponseDTO(

        @Schema(description = "Имя сервиса: по нему различают наши процессы в общем мониторинге",
                example = "hot-hat-back")
        String service,

        @Schema(description = "Всегда «up»: если процесс не жив, ответа не будет вовсе",
                example = "up", allowableValues = {"up"})
        String status) {
}
