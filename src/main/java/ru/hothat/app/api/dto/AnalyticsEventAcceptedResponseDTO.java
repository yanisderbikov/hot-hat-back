package ru.hothat.app.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Событие принято.
 *
 * <p>Ответ намеренно не говорит, записали событие или узнали в нём повтор.
 * Движок за этим адресом и сам этого не сообщает, а главное — клиенту нечего
 * с этим делать: он шлёт событие из обработчика, который срабатывает у
 * каждого участника партии, и «повтор» здесь нормальный ход дела, а не
 * ошибка. Отсюда и код 202: «принято к обработке», а не 201 «создано» —
 * старый адрес отвечал 201 в том числе на дубликат, которого не создавал.
 */
@Schema(description = "Подтверждение приёма события")
public record AnalyticsEventAcceptedResponseDTO(

        @Schema(description = "Ключ принятого события — тот же, что прислали",
                example = "hat-0f3a9c1d7b2e5480-game-2-finished")
        String eventKey) {
}
