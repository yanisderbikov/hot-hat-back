package ru.hothat.app.spi;

/**
 * Что область {@code app} отвечает соседям о рубильниках.
 *
 * <p>Спрашивают её тест-боты: их движок целиком выключается флагом
 * {@code bot_enabled}. Порт объявлен у владельца таблицы, чтобы соседу не
 * приходилось знать ни имени таблицы, ни того, что ответ кешируется.
 *
 * <p>Порт умышленно только читает: у флага один писатель — консоль
 * администратора, и появление здесь записи означало бы второго.
 */
public interface FeatureFlagPort {

    /** Включена ли возможность; неизвестное имя — {@code false}. */
    boolean enabled(String name);
}
