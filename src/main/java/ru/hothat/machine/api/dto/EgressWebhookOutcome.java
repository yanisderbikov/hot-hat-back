package ru.hothat.machine.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Что сервер сделал с уведомлением LiveKit.
 *
 * <p>Сегодня «не применили» выражается ключом {@code ignored:true} и строкой
 * причины, причём в двух разных местах — в контроллере и в сервисе. Здесь
 * причина одна и перечислима, и по ней можно строить дашборд, не разбирая
 * текст.
 */
@Schema(description = "Исход обработки уведомления LiveKit")
public enum EgressWebhookOutcome {

    /** Состояние записи обновлено. */
    APPLIED,

    /** Событие не про выгрузку: имя не начинается с egress_. */
    IGNORED_NOT_EGRESS_EVENT,

    /** В уведомлении нет блока состояния выгрузки. */
    IGNORED_NO_EGRESS_INFO,

    /** Записи для этой партии в базе нет. */
    IGNORED_RECORDING_NOT_FOUND,

    /** Уведомление относится к другой выгрузке той же партии. */
    IGNORED_EGRESS_ID_MISMATCH,

    /**
     * Ту же доставку уже применяли.
     *
     * <p>Исход новый, и появился он вместе с журналом уведомлений: раньше
     * отличить повтор было не по чему, и он применялся второй раз — завершение
     * записи, пришедшее дважды, дважды двигало её состояние. Потребитель этого
     * ответа — сам LiveKit, который тела не читает; фронтенд сюда не ходит.
     */
    IGNORED_DUPLICATE_DELIVERY
}
