package ru.hothat.machine.domain;

/**
 * Область машинного доступа: конкретная партия конкретной комнаты.
 *
 * <p>Нужна потому, что подпись рекордера и подпись вебхука считаются не от
 * секрета вообще, а от пары «комната + номер партии»
 * ({@code RecordingServiceImpl.viewSignature}). Значит, удостоверение говорит
 * не только «это рекордер», но и «это рекордер вот этой съёмки»: подписью от
 * чужой комнаты нашу не открыть.
 *
 * <p>Область берётся из пути, а не из тела и не из строки запроса. Из тела её
 * не взять принципиально: тело читает Jackson уже за фильтром, и проверка
 * подписи опять уехала бы внутрь метода — ровно туда, откуда её убирают.
 */
public record MachineScope(String roomId, int gameNumber) {

    /** У cron и агента мониторинга области нет: они работают по всей базе. */
    public static final MachineScope NONE = new MachineScope("", -1);

    public boolean present() {
        return !roomId.isEmpty() && gameNumber >= 0;
    }
}
