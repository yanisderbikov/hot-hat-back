package ru.hothat.room.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Принятая отметка активности хозяина.
 *
 * <p>Порог бездействия отдаётся ответом, а не держится константой в браузере:
 * сегодня три минуты вписаны литералом и на сервере, и в двух местах фронта, и
 * подсказка «комната перейдёт через 2:14» считается по клиентской копии.
 * Разойдись копии — человек увидел бы обратный отсчёт, не имеющий отношения к
 * тому, что произойдёт.
 *
 * <p>{@code accepted} различает два случая одной формой: отметка записана либо
 * пропущена, потому что комната уже не в наборе. Второе — не ошибка: экран
 * шлёт отметки по движению мыши и не обязан следить за фазой.
 */
@Schema(description = "Принятая отметка активности хозяина")
public record HostActivityResponseDTO(

        @Schema(description = "Отметка записана; false — комната уже не в наборе и сторож молчит",
                example = "true", type = "boolean")
        boolean accepted,

        @Schema(description = "Сколько времени бездействия комната прощает хозяину, миллисекунды",
                example = "180000", type = "integer")
        long idleLimitMs,

        @Schema(description = "Сколько осталось до передачи хозяйства, миллисекунды",
                example = "180000", type = "integer")
        long remainingMs) {
}
