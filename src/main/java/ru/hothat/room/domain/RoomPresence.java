package ru.hothat.room.domain;

/**
 * Кого считать живым в комнате.
 *
 * <p>Одно окно на всю область. Сегодня это число живёт в семи местах:
 * {@code GameServiceImpl.ACTIVE_PLAYER_WINDOW_MS}, {@code SocialServiceImpl}
 * (там оно вписано литералом {@code 300000}), плюс пять копий во фронтенде
 * ({@code app-core.js}: жеребьёвка, вход, вместимость, состав команды,
 * счётчик зрителей). Совпадали они только по счастливой случайности: у
 * зрителей во фронте окно другое, семь минут, и его пришлось назвать здесь
 * отдельной константой, а не «починить» в одну сторону — иначе зрители
 * начали бы пропадать из шапки на середине партии.
 *
 * <p>Класс без Spring и без базы: принимает готовые признаки, а не строку
 * игрока. Тогда правило нельзя случайно «улучшить» походом в базу.
 */
public final class RoomPresence {

    /**
     * Сколько игрок считается живым после последней отметки.
     *
     * <p>Пять минут — то же окно, с которым сегодня работают и сервер, и
     * браузер. Оно намеренно шире, чем витрина лобби (там четыре минуты):
     * в лобби ошибка стоит лишней строки в списке, а здесь — выброшенного из
     * своей команды человека, у которого просто заснул телефон.
     */
    public static final long PLAYER_WINDOW_MS = 5 * 60 * 1000;

    /**
     * Сколько живым считается зритель.
     *
     * <p>Семь минут, как в {@code activeSpectators()} во фронте. Зритель не
     * занимает места в команде и ничего не ломает, задержавшись в списке,
     * поэтому его окно щедрее.
     */
    public static final long SPECTATOR_WINDOW_MS = 7 * 60 * 1000;

    private RoomPresence() {
    }

    /**
     * Жив ли игрок.
     *
     * <p>Тест-бот жив всегда: он намеренно не шлёт отметок, и по общему
     * правилу выпал бы из комнаты через пять минут вместе со всей тестовой
     * партией.
     */
    public static boolean playerAlive(boolean testBot, long lastSeenAtMs, long nowMs) {
        return testBot || lastSeenAtMs >= nowMs - PLAYER_WINDOW_MS;
    }

    public static boolean spectatorAlive(long lastSeenAtMs, long nowMs) {
        return lastSeenAtMs >= nowMs - SPECTATOR_WINDOW_MS;
    }
}
