package ru.hothat.room.store;

import jakarta.persistence.LockModeType;
import org.springframework.data.jpa.repository.Lock;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.Repository;
import org.springframework.data.repository.query.Param;
import ru.hothat.model.room.Room;

import java.util.Collection;
import java.util.List;
import java.util.Optional;

/**
 * Строка комнаты, прочитанная под замком.
 *
 * <p>Это ответ на находку B2 аудита. Клиентские {@code runTransaction} —
 * рассадка, вход в команду, роспуск команды, сдача слов — переехали на сервер,
 * а всё, что было у них вместо блокировки, — сравнение {@code updatedAt} в
 * прежнем документном шлюзе. Сравнение читало, решало и писало тремя
 * отдельными шагами, между которыми умещалась чужая запись: это check-then-act,
 * и потерянное обновление он допускал. Здесь строка комнаты берётся
 * {@code select … for update} до первого чтения состава, поэтому два игрока,
 * одновременно севшие в последнее свободное место команды, выстраиваются в
 * очередь, а не затирают друг друга.
 *
 * <p>Есть и вторая причина, кроме гонки за место. У строки комнаты нет
 * частичного обновления: {@code Room} не помечена {@code @DynamicUpdate}, и
 * любая запись уносит в базу все её колонки разом — вместе с фазой, счётом и
 * составами, прочитанными до чужой правки (находка B7). Замок делает такое
 * затирание невозможным.
 *
 * <p><b>Почему замок, а не {@code @Version}.</b> Оптимистичная блокировка
 * требует колонки в нескольких таблицах и ветки на
 * {@code ObjectOptimisticLockingFailureException} в общем обработчике ошибок.
 * И то и другое — файлы за пределами этой области, а без второго каждый
 * реальный конфликт приезжал бы игроку пятисоткой вместо 409. Аудит называет
 * оба средства равноправными («{@code @Version} на сущностях документного шлюза
 * <i>или</i> чтение под {@code PESSIMISTIC_WRITE}»), и здесь выбрано то,
 * которое область может довести до конца сама.
 *
 * <p><b>Порядок замков.</b> Комната блокируется первой и единственной: всё
 * остальное в комнате — места, команды, чат, слова — пишется только после неё.
 * Тот же порядок держит у себя область партии, поэтому взаимной блокировки
 * между областями не получается в принципе.
 *
 * <p>Тип публичен, потому что им пользуется соседний пакет области. Наружу
 * области он не выходит: за границу ездят DTO и порты.
 *
 * <p>Стереотипа над объявлением нет намеренно: бин интерфейсу-репозиторию
 * создаёт Spring Data сам, а {@code @Repository} из пакета стереотипов
 * столкнулся бы простым именем с базовым {@code Repository} Spring Data —
 * ровно тем, который здесь расширяется.
 */
public interface RoomRows extends Repository<Room, String> {

    /**
     * Комната под замком записи; замок держится до конца транзакции.
     *
     * <p>Пусто — комнаты нет, и блокировать нечего.
     */
    @Lock(LockModeType.PESSIMISTIC_WRITE)
    @Query("select r from Room r where r.id = :roomId")
    Optional<Room> lock(@Param("roomId") String roomId);

    /**
     * Комнаты названных приглашений — одним запросом.
     *
     * <p>Существует ради единственного места, где комнат сразу много: страница
     * переписки спрашивает состояние до шестидесяти приглашений разом, и у
     * каждого своя комната. Старый движок ходил за ними по одной, сглаживая
     * это картой в памяти метода, — до шестидесяти обращений на открытие чата.
     *
     * <p>Замок здесь не нужен: это чтение для показа, ничего не пишущее.
     */
    @Query("select r from Room r where r.id in :roomIds")
    List<Room> findAll(@Param("roomIds") Collection<String> roomIds);
}
