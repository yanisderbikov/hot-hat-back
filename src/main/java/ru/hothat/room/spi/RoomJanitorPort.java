package ru.hothat.room.spi;

import java.util.List;

/**
 * Уборка брошенных комнат — дверь для тех, кто её заказывает.
 *
 * <p>Комнату убирает её область: у строки один писатель, и удаление — такая же
 * запись, как остальные. Заказчиков трое: сам выход из комнаты (там уборка —
 * инвариант выхода, а не вежливость вкладки), плановый проход машинного
 * контура и прежний адрес {@code /api/cleanup-rooms}.
 *
 * <p>Порт отвечает записями, а не {@code Map}: у ответа два разных исхода —
 * «убрали» и «не убрали, потому что…», — и различать их по наличию ключа в
 * карте значило бы описывать одно понятие двумя формами.
 */
public interface RoomJanitorPort {

    /**
     * Убрать названную комнату, если она брошена.
     *
     * <p>Фора только что созданной комнате здесь не действует: про эту комнату
     * спросили прямо, и ответ «подожди две минуты» никому не нужен.
     */
    Cleanup cleanupOne(String roomId);

    /** Общий проход. Чаще кулдауна не запускается — второй вызов вернёт {@code skipped}. */
    Sweep sweep();

    /**
     * Итог точечной уборки.
     *
     * @param reason почему убрали или почему оставили; это же значение
     *               показывает ответ прежнего адреса
     */
    record Cleanup(String roomId, boolean deleted, String reason) {
    }

    /**
     * Итог общего прохода.
     *
     * @param skipped прогон не состоялся: предыдущий был меньше кулдауна назад
     * @param checked сколько комнат прочитали
     */
    record Sweep(boolean skipped, int checked, List<Swept> rooms) {
    }

    /** Убранная комната и причина. */
    record Swept(String roomId, String reason) {
    }
}
