package ru.hothat.room.spi;

import java.util.Optional;

/**
 * Справка о комнате для соседних областей.
 *
 * <p>Порт объявлен у владельца таблиц, как {@link RoomNicknamePort}: комнату
 * читает и пишет её область, остальные спрашивают. До сих пор спрашивали
 * иначе — три области схемы v2 (профиль, тест-боты, команда) держали у себя
 * {@code GetterRoom} и разбирали сущность {@code Room} на 103 колонки, чтобы
 * задать ей вопрос на «да» или «нет». Из-за этого условие «своя тестовая
 * комната» было записано дважды: приватным методом внутри движка ботов и
 * копией в сторожевом классе, и копии полагалось совпадать на честном слове.
 *
 * <p>Порт умышленно только читает. Заводить, закрывать и переименовывать
 * комнату продолжает её область: у колонки один писатель, и появление здесь
 * первой же записи означало бы второго.
 *
 * <p>Сущность комнаты наружу не выходит — едет запись с полями, которые
 * спрашивают. Это и есть разница с {@code GetterRoom}: соседу не нужно знать,
 * что вместимость лежит в двух колонках сразу, а хозяин — в той же, что автор.
 */
public interface RoomDirectoryPort {

    /**
     * Есть ли такая комната вовсе.
     *
     * <p>Отдельным вопросом, а не {@code find(id).isPresent()}: спрашивают его
     * ради отметки «я сейчас играю здесь», и читать ради этого всю строку
     * комнаты незачем.
     */
    boolean exists(String roomId);

    /** Комната в объёме, который нужен соседям; пусто — комнаты нет. */
    Optional<RoomBrief> find(String roomId);

    /**
     * Комната глазами соседа.
     *
     * @param hostUid     кто ведёт комнату сейчас
     * @param testOwnerUid чей это тестовый прогон; {@code null} — комната не тестовая
     * @param gameNumber  номер идущей партии: по нему гаснут старые приглашения
     */
    record RoomBrief(String roomId,
                     String name,
                     String hostUid,
                     String phase,
                     boolean closed,
                     boolean ranked,
                     boolean testRoom,
                     String testOwnerUid,
                     String gameMode,
                     String divisionLanguage,
                     int gameNumber) {

        /** Комната ещё набирается: партия не начата и не закрыта. */
        public boolean open() {
            return !closed && "setup".equals(phase);
        }

        /**
         * Это тестовая комната названного админа.
         *
         * <p>Правило живёт здесь, а не у спрашивающего: админов больше одного,
         * тестовых комнат тоже, и разные ответы на один вопрос развели бы
         * права по разным адресам.
         */
        public boolean ownedTestRoomOf(String uid) {
            return testRoom && testOwnerUid != null && testOwnerUid.equals(uid);
        }
    }
}
