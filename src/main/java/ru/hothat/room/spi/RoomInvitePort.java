package ru.hothat.room.spi;

import java.util.Collection;
import java.util.Map;

/**
 * Приглашение в комнату глазами соседа.
 *
 * <p>Спрашивает переписка: карточка приглашения живёт сообщением в диалоге, а
 * знает о нём только ссылку. Комната, её название и поколение партии
 * принадлежат области комнаты — держать их копию в сообщении значило бы
 * завести второго писателя у названия комнаты, которое меняется.
 *
 * <p>Порт читает пачкой и только пачкой: страница истории показывает до
 * тридцати сообщений, и вопрос по каждому вернул бы веер чтений, ради
 * устранения которого переписка и переехала (находка B8).
 */
public interface RoomInvitePort {

    /**
     * Карточки названных приглашений.
     *
     * <p>Приглашения, которого нет, в ответе не будет: сообщение о нём
     * останется без карточки, и это честнее выдуманной комнаты.
     */
    Map<String, InviteCard> cards(Collection<String> inviteIds);

    /**
     * Столько, сколько нужно кнопке «войти».
     *
     * @param gameNumberAtInvite поколение партии на момент приглашения: по нему
     *                           гаснет ссылка, выданная до старта игры
     */
    record InviteCard(String inviteId, String roomId, String roomName, int gameNumberAtInvite) {
    }
}
