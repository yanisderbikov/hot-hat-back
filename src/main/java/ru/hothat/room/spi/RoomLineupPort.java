package ru.hothat.room.spi;

/**
 * Комната под готовый состав — глазами видео-чата.
 *
 * <p>Видео-чат умеет «создать комнату этим составом»: хозяин созвона нажимает
 * кнопку, и все, кто был в звонке, переходят в приватную комнату. Комнату
 * при этом заводит её область, как и любую другую, — видео-чат лишь просит.
 * Иначе у строки комнаты оказалось бы два писателя из разных областей.
 *
 * <p>Командный порт (§7.3): запись идёт внутри транзакции просящего —
 * комната и отметка о ней в видео-чате ложатся вместе или не ложатся вовсе.
 * Своей транзакции здесь нет намеренно: {@code MANDATORY}.
 */
public interface RoomLineupPort {

    /**
     * Завести приватную комнату и посадить в неё хозяина.
     *
     * <p>Правила те же, что у кнопки «Создать игру» на главной: пять
     * заряженных мемов обязательны, имя и дивизион берутся из карточки
     * хозяина. Остальных участников комната не сажает — они входят сами по
     * ссылке, каждый со своей обоймой и своей проверкой допуска.
     *
     * @return идентификатор новой комнаты
     * @throws ru.hothat.config.ApiException 409 {@code DEFAULT_LOADOUT_REQUIRED}
     */
    String openPrivateRoom(PrivateRoomOrder order);

    /**
     * Заказ на приватную комнату.
     *
     * @param capacity сколько мест: чётное от 4 до 10
     */
    record PrivateRoomOrder(String hostUid, String name, int capacity) {
    }
}
