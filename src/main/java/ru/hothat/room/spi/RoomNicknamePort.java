package ru.hothat.room.spi;

/**
 * Что соседи вправе попросить область комнаты изменить в копиях имени.
 *
 * <p>Копии тут действительно есть, и это не забытая грязь: место игрока
 * (`room_player.name`), место зрителя, карта имён партии
 * (`room.gamePlayerNamesByUid`) и подписи объясняющего и отгадывающего хранят
 * имя снимком — им нужно то имя, под которым человек играл, а не нынешнее.
 * Пока комната не переехала на схему v2, копии остаются, и кто-то обязан их
 * подновлять при смене ника.
 *
 * <p>Раньше это делал сам движок профиля, ходя в таблицы комнаты напрямую.
 * Теперь просит — а пишет владелец, как и положено. Заодно исчез веер: у
 * игрока, сидящего в двух комнатах, обход стоил двух чтений комнаты внутри
 * цикла по местам.
 *
 * <p>Порт умрёт вместе с переездом комнаты: в v2 состав партии замораживается
 * в {@code match_player.display_name}, а место в комнате имени не хранит вовсе.
 */
public interface RoomNicknamePort {

    /**
     * Подновить копии имени во всех комнатах, где игрок сейчас числится.
     *
     * @return сколько комнат тронуто
     */
    int renameEverywhere(String uid, String nickname);

    /**
     * Подновить копию имени в одной названной комнате.
     *
     * @return {@code false} — такой комнаты нет либо игрок в ней не числится
     */
    boolean renameIn(String roomId, String uid, String nickname);
}
