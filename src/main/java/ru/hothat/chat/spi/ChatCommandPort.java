package ru.hothat.chat.spi;

/**
 * Что соседи вправе попросить записать в переписку.
 *
 * <p>Командный порт (§7.3): изменение чужих данных внутри текущей транзакции.
 * Пишет по-прежнему владелец — область переписки, — а зовущий лишь просит.
 * Просит один: приглашение в комнату. Оно обязано лечь вместе с самим
 * приглашением, одной транзакцией: карточка в диалоге без приглашения — это
 * кнопка, ведущая в отказ, а приглашение без карточки не увидит никто.
 *
 * <p>Событием это разорвать нельзя, и в плане так и записано: события носят
 * только то, что вправе опоздать, а здесь речь об инварианте.
 */
public interface ChatCommandPort {

    /**
     * Кому этот человек вправе писать.
     *
     * <p>Вопрос чужой области, но задаёт его комната — до того, как заведёт
     * приглашение: правило «кому можно писать» одно на все пять адресов
     * переписки, и вторая его копия в комнате разошлась бы с первой.
     *
     * @return uid собеседника в том виде, в каком его понимает хранилище
     * @throws ru.hothat.config.ApiException 403 или 409 {@code FRIEND_REQUIRED}
     */
    String requireWritablePeer(String selfUid, String peerUid);

    /**
     * Положить в переписку карточку приглашения в комнату.
     *
     * <p>Делает три вещи разом, потому что порознь они бессмысленны: пишет
     * сообщение, поднимает счётчик непрочитанного собеседника и будит живой
     * канал диалога. Строка переписки заводится, если её ещё не было.
     *
     * @return идентификатор записанного сообщения
     */
    long appendRoomInvite(RoomInviteCard card);

    /**
     * Погасить в значке входящих отметку «вас позвали».
     *
     * <p>Зовёт принятие приглашения. Строка входящих принадлежит переписке, и
     * писать её из области комнаты значило бы дать значку второго писателя;
     * приглашение при этом остаётся у комнаты — гасится только карточка.
     *
     * @param inviteId приглашение, которое приняли; если в значке стоит другое,
     *                 не трогается ничего — там уже более свежее событие
     */
    void markRoomInviteAccepted(String uid, String inviteId);

    /**
     * Приглашение так, как его показывают в диалоге.
     *
     * @param text  строка, которую видно превью в списке переписок
     */
    record RoomInviteCard(String fromUid, String toUid, String inviteId, String roomId,
                          String roomName, String fromNickname, String text) {
    }
}
