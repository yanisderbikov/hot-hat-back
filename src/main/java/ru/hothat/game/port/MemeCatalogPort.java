package ru.hothat.game.port;

import ru.hothat.game.domain.weapon.MemeMedia;

import java.util.Collection;
import java.util.Optional;
import java.util.Set;

/**
 * Библиотека мемов глазами партии.
 *
 * <p>Партии нужна ровно одна вещь — можно ли показать этот ролик и сколько он
 * длится. Права на мем, его владелец, размер файла и история загрузок остаются
 * в области медиа: диверсия не должна уметь их читать.
 */
public interface MemeCatalogPort {

    /** Ролик, готовый к показу; пусто — мем удалён или выключен. */
    Optional<MemeMedia> find(String memeId);

    /** Существует ли мем: проверка при замене одного слота, без сборки ссылок. */
    boolean exists(String memeId);

    /**
     * Какие из этих мемов существуют — одним чтением.
     *
     * <p>Обойма заряжается сразу пятью роликами, и спрашивать про каждый
     * отдельно значило бы пять чтений на один запрос. Возвращается не «да/нет»
     * на весь список, а найденное подмножество: вызывающему бывает нужно
     * назвать, чего именно не хватило.
     */
    Set<String> existing(Collection<String> memeIds);
}
