package ru.hothat.game.domain;

/**
 * Дорожка эффекта, которую занимает диверсия.
 *
 * <p>Дорожек четыре, и одновременно на объясняющем может действовать по одной
 * диверсии с каждой: картинка, голос, крокодил и накладка. Именно поэтому
 * «занято» — это не один флаг, а четыре независимых срока: негатив и маска
 * спорят между собой, но не мешают голосу.
 */
public enum EffectLock {

    /** Картинка объясняющего: негатив и маска Кита Пено. */
    VIDEO,
    /** Голос объясняющего: три голосовых эффекта. */
    VOICE,
    /** Крокодил: объясняющему запрещено говорить до конца хода. */
    CROCODILE,
    /** Накладка поверх сцены: объект, какахи, мега текст. */
    OVERLAY,
    /** Подмена картинки заранее снятым клипом. */
    REPLACEMENT,
    /** Оружие без эффекта на сцене: помидор, мем, пук. */
    NONE
}
