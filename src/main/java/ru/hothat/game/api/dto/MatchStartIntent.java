package ru.hothat.game.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Что именно начинают: первую партию или следующую.
 *
 * <p>Клиент называет это сам, хотя сервер видит фазу комнаты и мог бы
 * догадаться. Причина — двойное нажатие: кнопка «Начать игру» и кнопка
 * «Играть ещё» ведут из разных состояний, и намерение, разошедшееся с фазой,
 * означает, что человек нажал на устаревшем экране. Такое лучше отвергнуть,
 * чем начать не ту партию.
 */
@Schema(description = "Из какого состояния начинают партию")
public enum MatchStartIntent {

    /** Из набора: команды собраны, слова сданы. */
    FIRST_GAME,
    /** Из экрана итогов: те же команды играют снова. */
    REMATCH
}
