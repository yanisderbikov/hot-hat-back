package ru.hothat.game.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Занятость дорожек эффектов на сцене.
 *
 * <p>Каждое поле — момент серверного времени, до которого дорожка занята;
 * ноль — свободна. Кнопки панели диверсий гаснут по этим срокам
 * ({@code app-core.js:1772}): пока по объясняющему идёт видеоэффект, второй
 * поверх него не пустят.
 *
 * <p>Съёмка Подмены заперта поимённо, и наружу выходит только <b>свой</b>
 * срок: по чужим срокам съёмки видно, кто и когда готовит Подмену, а это то
 * же знание, из-за которого чужие клипы не отдаются никому. Проекция поэтому
 * собирается на слушателя, как и слово хода.
 */
@Schema(description = "Занятость дорожек эффектов")
public record SabotageLocksView(

        @Schema(description = "До какого момента занята видеодорожка, миллисекунды эпохи; 0 — свободна",
                example = "1757150390000")
        long videoUntil,

        @Schema(description = "До какого момента занята голосовая дорожка, миллисекунды эпохи; 0 — свободна",
                example = "0")
        long voiceUntil,

        @Schema(description = "До какого момента объясняющий молчит крокодилом, миллисекунды эпохи; 0 — говорит",
                example = "0")
        long crocodileUntil,

        @Schema(description = "До какого момента занята накладка на сцене, миллисекунды эпохи; 0 — свободна",
                example = "0")
        long overlayUntil,

        @Schema(description = "До какого момента идёт Подмена, миллисекунды эпохи; 0 — не идёт",
                example = "0")
        long replacementUntil,

        @Schema(description = "Ход, в котором Подмена уже была: второй раз за ход её не применить; "
                + "пустая строка — ещё не было", example = "turn_3f9a1c04b77e2d15")
        String replacementTurnId,

        @Schema(description = "До какого момента идёт своя съёмка Подмены, миллисекунды эпохи; "
                + "0 — не идёт. Чужие съёмки не показываются", example = "0")
        long replacementRecordingUntil) {
}
