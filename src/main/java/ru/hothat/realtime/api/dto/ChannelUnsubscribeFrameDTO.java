package ru.hothat.realtime.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Отказ от подписки, не закрывающий соединение.
 *
 * <p>Точный наследник {@code {type:"unsubscribe", id}} прежнего документного
 * шлюза. Нужен там, где у канала есть вторая, сменная
 * подписка: главная держит лобби открытым, а превью выбранной комнаты
 * переключает каждые тридцать секунд, — и снимать превью закрытием сокета
 * значило бы заново здороваться и заново проверять токен дважды в минуту.
 *
 * <p>Ответного кадра нет намеренно. Клиент только что попросил перестать
 * присылать ему кадры этой подписки; ответить ему кадром было бы ровно тем,
 * от чего он отказался. Закрытие сокета кодом 1000 остаётся вторым, более
 * грубым способом — сервер снимает регистрацию и в нём.
 */
@Schema(description = "Снять подписку, не закрывая канал")
public record ChannelUnsubscribeFrameDTO(

        @Schema(description = "Имя кадра", example = "unsubscribe", allowableValues = "unsubscribe")
        String type,

        @Schema(description = "Какую подписку снять. У канала с одним предметом поле пустое и "
                + "означает сам канал; у лобби значение spotlight снимает превью комнаты",
                example = "spotlight", nullable = true)
        String id) {
}
