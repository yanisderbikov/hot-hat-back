package ru.hothat.realtime.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Всё, что показывает игровой экран, — одним кадром.
 *
 * <p>Общая проекция обоих кадров канала {@code /ws/v2/room/{roomId}}:
 * приветственного и обновляющего.
 *
 * <p>Здесь сходятся шесть прежних подписок браузера: документ комнаты, места,
 * составы, зрители, чат и свои слова ({@code app-core.js:8704}, {@code :8820},
 * {@code :8831}, {@code :8858}, {@code :8865}, {@code :8876}). Шестью они были
 * не по смыслу, а по устройству прежнего хранилища, и приезжали вразнобой —
 * отсюда мигание пустого стола на входе и стол без счёта.
 *
 * <p>Каждое поле — форма своего адреса HTTP, поле в поле: снимок комнаты,
 * страница чата, состояние партии, свои слова. Кадр не изобретает ни одной
 * собственной формы, и у экрана остаётся одна ветка отрисовки на каждый
 * предмет вместо двух.
 *
 * <p>Снимок целиком, а не дельта: комната небольшая, а перечитывание надёжнее
 * склейки приращений и не расходится с базой.
 *
 * <p>Имена полей здесь — имена API v2 ({@code uid}, {@code teamId},
 * {@code …AtMs}), а не ключи документа комнаты, которыми экран жил до
 * переезда: те же записи отдают два десятка адресов HTTP. Что и куда экран
 * переводит на границе — в {@code docs/api/03-room-channel-adapter.md}.
 */
@Schema(description = "Состояние комнаты, составов, чата и партии")
public record RoomChannelView(

        @Schema(description = "Комната, места, составы и зрители")
        RoomSnapshotView snapshot,

        @Schema(description = "Хвост чата комнаты")
        RoomChatWindowView chat,

        @Schema(description = "Состояние партии глазами слушателя")
        RoomMatchView match,

        @Schema(description = "Свои слова в шляпе")
        RoomWordsView words) {
}
