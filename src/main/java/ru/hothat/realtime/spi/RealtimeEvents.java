package ru.hothat.realtime.spi;

/**
 * Что изменилось — в терминах именованных каналов, а не таблиц.
 *
 * <p>Событие здесь означает ровно одно: «снимок такого-то канала устарел,
 * подписчикам пора прислать новый». Данные оно не несёт и нести не должно.
 * Причина не в экономии: канал обязан отдавать <b>ту же проекцию</b>, что и
 * соответствующий адрес HTTP, и собирает её сценарий канала — на того, кто
 * слушает. Если бы данные ехали в событии, их собрал бы писатель, не знающий
 * ни слушателя, ни его прав, и вторая форма одного и того же списка появилась
 * бы снова — та самая, из-за которой переписка держала во фронте две ветки
 * отрисовки.
 *
 * <p>Область {@code spi}, а не {@code usecase}: контракт объявлен здесь, а
 * пользуются им писатели из других областей. Направление зависимости выбрано
 * так намеренно — тот, кто пишет, не должен знать ни про сокеты, ни про кадры.
 *
 * <p>Публикуется всё это <b>только</b> через {@link RealtimeChangeBus}: он
 * снимает повторы внутри одной транзакции. Прямой {@code publishEvent} тоже
 * сработает, но пять сохранённых мест комнаты дадут пять одинаковых рассылок.
 *
 * <p>Слушают события обработчики каналов, и делают это после фиксации —
 * {@code @TransactionalEventListener(AFTER_COMMIT)}. До неё подписчик увидел
 * бы состояние, которого при откате не станет.
 */
public final class RealtimeEvents {

    private RealtimeEvents() {
    }

    /**
     * Комната изменилась: паспорт, места, составы, зрители, чат, слова или ход.
     *
     * <p>Одно событие на всю комнату, а не по одному на каждую её часть.
     * Канал {@code /ws/v2/room/{roomId}} присылает снимок целиком — тем же
     * набором, каким его отдаёт {@code GET /api/v2/room/{roomId}}, — и делить
     * событие значило бы описывать в нём внутренности снимка.
     */
    public record RoomChanged(String roomId) {
    }

    /**
     * Витрина открытых комнат изменилась.
     *
     * <p>Без параметров: витрина одна на всех, а кому какая комната видна,
     * решает сценарий чтения — приватную и чужую тестовую он не покажет.
     */
    public record LobbyChanged() {
    }

    /**
     * Личное социальное состояние игрока: заявки, входящие, бан.
     *
     * @param uid чьё именно; рассылка идёт только его сокетам
     */
    public record SocialChanged(String uid) {
    }

    /** Проверка готовности рейтинговой пары изменилась. */
    public record PreflightChanged(String teamId) {
    }

    /** Общая библиотека мемов изменилась. */
    public record MemeLibraryChanged() {
    }

    /**
     * Видео-чат изменился: состав, приглашения, чат или заведённая из него
     * комната.
     *
     * <p>Одно событие на весь видео-чат, как у комнаты: канал
     * {@code /ws/v2/conference/{id}} присылает снимок целиком.
     */
    public record ConferenceChanged(String conferenceId) {
    }
}
