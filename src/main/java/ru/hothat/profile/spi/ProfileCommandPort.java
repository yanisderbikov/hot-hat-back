package ru.hothat.profile.spi;

/**
 * Что соседи вправе попросить область {@code profile} изменить.
 *
 * <p>Ровно одно: завести карточку. Просит регистрация — учётка без имени
 * непредставима, а заводить их двумя запросами значило бы допустить учётку,
 * у которой имени ещё нет (§7.3, строка «Регистрация»). Пишет по-прежнему
 * владелец таблицы: сосед называет игрока и имя, а не трогает
 * {@code v2.player_profile} сам.
 *
 * <p>Командный порт, а не событие: карточка обязана лечь в ту же транзакцию,
 * что и учётка.
 */
public interface ProfileCommandPort {

    /**
     * Завести карточку вместе с учёткой.
     *
     * @param nickname имя, уже проверенное на форму и свободу вызывающим;
     *                 последнее слово всё равно за уникальным индексом базы
     */
    void createCard(String uid, String nickname, String divisionLanguage);

    /**
     * Свободное имя, похожее на подсказку: им пользуется гостевой вход, где
     * имени игрока ещё нет вовсе.
     */
    String freeNicknameFrom(String hint, String uid);

    /**
     * Карточка есть — ничего не делать; нет — завести с придуманным именем.
     *
     * <p>Существует ради учёток, заведённых до переезда: показать их надо, а
     * строки карточки у них нет. Новые приходят сюда уже с карточкой.
     */
    void ensureCard(String uid, String nameHint);
}
