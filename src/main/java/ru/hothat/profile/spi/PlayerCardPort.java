package ru.hothat.profile.spi;

import java.time.Instant;
import java.util.Collection;
import java.util.Map;
import java.util.Optional;

/**
 * Что область {@code profile} отвечает соседям о карточке игрока.
 *
 * <p>Спрашивают её все, кто рисует человека: списки друзей и переписок,
 * составы комнат и партий, таблицы сезона, дашборд администратора. Раньше
 * каждый из них держал свою копию ника и аватара в собственной таблице, и
 * копии устаревали в тот же миг, когда игрок менял имя: таблица сезона
 * показывала прежний ник до конца сезона, а строка места в комнате — до
 * следующего входа. Теперь копий нет, а проекция собирается на чтении.
 *
 * <p>Порт, а не общий репозиторий: соседняя область не получает доступа к
 * {@code v2.player_profile} и не может завести второго хозяина у имени.
 */
public interface PlayerCardPort {

    /** Карточка игрока; пусто — карточки нет. */
    Optional<Card> card(String uid);

    /**
     * Карточки названных игроков разом. Стол на восьмерых, сотня друзей и
     * страница рейтинга стоят одинаково — три запроса, а не по три на
     * человека.
     */
    Map<String, Card> cards(Collection<String> uids);

    /**
     * Ник для показа: имя из карточки, а у пропавшей — заглушка, которой
     * игрока подписывали и раньше. Отдельным методом, потому что заглушка
     * должна быть одна на весь сервис: «Игрок» в списке друзей и «player…» в
     * составе комнаты — это два разных человека на одном экране.
     */
    String nicknameOf(String uid);

    /** Чья это карточка по нику; пусто — ник свободен либо непригоден по форме. */
    Optional<String> uidByNickname(String nickname);

    /**
     * То же, но отказом вместо пустоты — коды те же, что были у старого движка,
     * и экраны их уже разбирают: 400 {@code NICKNAME_INVALID} у непригодного по
     * форме, 404 {@code PLAYER_NOT_FOUND} у свободного.
     */
    String requireUidByNickname(String nickname);

    /** Свободен ли ник: это спрашивают и форма регистрации, и онбординг. */
    boolean nicknameTaken(String nickname);

    /**
     * Сколько игроков отмечалось начиная с этого мгновения. Считает база по
     * индексу присутствия; раньше тот же счёт шёл последовательным чтением
     * всей таблицы учёток.
     */
    long onlineSince(Instant since);

    /**
     * Карточка в объёме, который нужен соседям: имя, аватар, дивизион, язык и
     * присутствие. Ни почты, ни поколения токенов — это другая область.
     */
    record Card(String uid, String nickname, String avatarDataUrl,
                String divisionLanguage, String uiLanguage, long lastSeenAtMs, String activeRoomId) {
    }
}
