package ru.hothat.profile.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Собственный профиль игрока.
 *
 * <p>Сегодня эти сведения приезжают внутри {@code ensure_profile} вместе с
 * обоймой мемов и квотой диверсий — тремя разными хозяйствами в одном ответе.
 * Здесь остаётся карточка и счётчик обоймы; сама обойма и квота живут по
 * своим адресам.
 *
 * <p>Счётчик обоймы всё же здесь, а не только у обоймы. Причина в том, кому он
 * нужен: главная страница показывает «3/5» и решает, пускать ли в игру, но
 * пять идентификаторов мемов ей ни к чему. Второй запрос ради одного числа
 * стоил бы дороже, чем это число весит.
 */
@Schema(description = "Профиль текущего игрока")
public record MyProfileResponseDTO(

        @Schema(description = "Карточка игрока")
        ProfileCardView profile,

        @Schema(description = "Насколько собрана обойма мемов")
        MemeLoadoutStatusView memeLoadout) {
}
