package ru.hothat.sabotage.spi;

import java.util.Collection;
import java.util.List;
import java.util.Map;

/**
 * Дверь, через которую чужие области спрашивают снаряжение диверсий.
 *
 * <p>Порт объявлен у владельца таблиц, как {@code team.spi} и {@code room.spi}:
 * право играть с диверсиями и стартовая обойма принадлежат этой области, и
 * писать в её таблицы продолжает она. Спрашивают все — вход в комнату,
 * подбор, префлайт команды, экран арсенала, — и до сих пор спрашивали через
 * {@code ProfileService}, то есть через движок профиля, которому эти два
 * хозяйства достались по наследству и никогда не принадлежали.
 *
 * <p>Идентификатор игрока здесь строковый, а не {@code AppUser}: оболочка
 * учётки к снаряжению отношения не имеет, и передавать её значило бы требовать
 * чтения таблицы {@code app_user} ради вопроса, который к ней не относится.
 */
public interface SabotageArmoryPort {

    /**
     * Сколько мемов игрок заряжает перед партией.
     *
     * <p>Число объявлено здесь, у владельца обоймы, и больше нигде. До сих пор
     * оно жило константой в правилах партии, и спрашивали её через голову
     * области — комната при посадке игрока, профиль при показе счётчика
     * «заряжено n из пяти». Обойма принадлежит диверсиям, значит и её размер
     * называет их порт.
     */
    int LOADOUT_SIZE = 5;

    /**
     * Квота партий с диверсиями.
     *
     * <p>Читает и пишет: друг владельца сервиса получает безлимит навсегда
     * именно в этот момент, иначе дружбу пришлось бы перепроверять при каждом
     * заходе на главную.
     *
     * @param email почта нужна ровно для одной проверки — «это владелец
     *              сервиса»; в снаряжении её нет и быть не должно
     */
    Entitlement entitlement(String uid, String email);

    /**
     * Засчитать начатую партию в квоту.
     *
     * <p>Повтор той же партии не тратит вторую: клиент шлёт списание сразу
     * после старта и повторяет его при переподключении. Исчерпанная квота —
     * отказ 402 {@code SABOTAGE_LIMIT_REACHED}.
     *
     * @return {@code true} — партия списана именно этим вызовом
     */
    boolean consume(String uid, String roomId, int gameNumber);

    /** Стартовая обойма игрока по порядку слотов; пустая — обоймы нет. */
    List<String> loadout(String uid);

    /**
     * Она же, но с требованием полноты: пять заряженных мемов обязательны для
     * входа в игру. Неполная обойма — отказ 409 {@code DEFAULT_LOADOUT_REQUIRED}.
     */
    List<String> requireLoadout(String uid);

    /** Обоймы названных игроков разом: подбор и префлайт спрашивают всю пару. */
    Map<String, List<String>> loadouts(Collection<String> uids);

    /**
     * Они же с требованием полноты у каждого.
     *
     * <p>Существует затем, что рейтинговая пара и подбор проверяют обойму сразу
     * у всех участников: без этого метода правило «ровно пять» пришлось бы
     * копировать в обе области, а спрашивать обоймы — по одной в цикле.
     * Неполная обойма хотя бы у одного — отказ 409
     * {@code DEFAULT_LOADOUT_REQUIRED} на всю партию: играть впятером против
     * четверых нельзя.
     */
    Map<String, List<String>> requireLoadouts(Collection<String> uids);

    /** Заменить обойму целиком; в ответе — что действительно записано. */
    List<String> saveLoadout(String uid, List<String> memeIds);

    /**
     * Полна ли обойма, записанная где-то ещё.
     *
     * <p>Спрашивает комната: место игрока хранит свою копию обоймы, и старые
     * сборки заводили её неполной через приглашение — такой игрок доходил до
     * старта партии, где вся комната упиралась в отказ «у игрока меньше пяти
     * мемов». Правило «полна» здесь ровно то же, что при чтении обоймы:
     * пустые и повторы не считаются.
     */
    boolean loadoutCharged(List<String> memeIds);

    /**
     * Стартовый боезапас партии: ключ снаряда → сколько его дают.
     *
     * <p>Спрашивает комната, заводя место игрока. Копия этого набора жила
     * тремя списками — в браузере, в создании комнаты и в приглашении, — и
     * серверные копии успели усохнуть до семи видов из десяти. Набор
     * выводится из каталога оружия, поэтому разойтись с ним ему нечем.
     */
    Map<String, Integer> baseArsenal();

    /**
     * Квота глазами спрашивающего.
     *
     * @param remaining сколько бесплатных партий осталось; {@code null} при
     *                  безлимите — ноль означал бы «партии кончились», то есть
     *                  ровно обратное
     */
    record Entitlement(boolean allowed, boolean unlimited, Integer remaining) {
    }
}
