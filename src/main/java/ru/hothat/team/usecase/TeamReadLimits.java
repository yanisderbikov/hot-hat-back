package ru.hothat.team.usecase;

/**
 * Числа, которые область команды обязана называть одинаково в базе и в ответе.
 *
 * <p>Перенесены из старого движка ({@code TeamServiceImpl}) без изменений:
 * переезд на v2 не должен менять то, что видит игрок. Держатся вместе, а не по
 * use-case, потому что каждое из них называет и ответ: предел списка обязан
 * совпасть с тем, с чем ходили в базу, иначе клиент не поймёт, полон ли
 * список, а срок жизни флага связи клиент показывает участнику.
 */
public final class TeamReadLimits {

    /** Приглашений в команды за раз — столько же читает {@code myTeam}. */
    public static final int INVITES = 10;

    /**
     * Флаг «камера и микрофон работают» протухает за 25 секунд.
     *
     * <p>Копия приватной константы {@code TeamServiceImpl.MEDIA_FLAG_TTL_MS}:
     * взять её оттуда нельзя, она не видна, а ответ обязан назвать срок —
     * иначе клиент продолжит держать его собственной константой, как держит
     * сейчас. Когда движок переедет сюда, копия останется одна.
     */
    public static final long MEDIA_FLAG_TTL_MS = 25_000L;

    /**
     * Проверка готовности живёт пять минут.
     *
     * <p>Перенесена из {@code TeamServiceImpl.PREFLIGHT_TTL_MS}: срок считает
     * сервер и кладёт в колонку {@code expires_at}, а клиент сравнивает с
     * присланными отметками времени, а не со своими часами.
     */
    public static final long PREFLIGHT_TTL_MS = 5 * 60 * 1000L;

    private TeamReadLimits() {
    }
}
