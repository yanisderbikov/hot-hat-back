package ru.hothat.team.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Комната-лобби команды: точка сбора пары перед рейтинговой игрой.
 *
 * <p>Адрес идемпотентен: у команды всегда одна и та же комната, её
 * идентификатор выводится из идентификатора команды. Повторный вызов чинит
 * комнату (фаза, состав, приватность) и возвращает тот же адрес, а не заводит
 * вторую.
 *
 * <p>Карточка команды едет вместе с комнатой не для украшения: клиент сразу
 * после подключения раскладывает участников по видеосетке и подписывает их
 * именами, и без состава ему пришлось бы вторым запросом идти за своей
 * командой.
 */
@Schema(description = "Лобби команды")
public record TeamLobbyResponseDTO(

        @Schema(description = "Комната команды: приватная, на двоих, с постоянным адресом",
                example = "hat-0f3a9c1d7b2e5480", pattern = "^hat-[a-f0-9]{16}$")
        String roomId,

        @Schema(description = "Карточка команды, которую только что рассадили в комнату")
        TeamCardView team) {
}
