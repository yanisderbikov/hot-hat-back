package ru.hothat.team.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Принятый отчёт о связи.
 *
 * <p>Снимка проверки здесь намеренно нет, хотя соседние адреса его отдают:
 * клиент шлёт этот отчёт раз в полторы секунды, и возить в ответ на каждый
 * удар весь состав с никами и флагами — платить за то, что уже приехало по
 * адресу чтения.
 *
 * <p>Зато едет серверное время: по нему клиент понимает, когда протухнет его
 * флаг, не сверяясь со своими часами. Раньше он держал этот срок константой у
 * себя и слал отчёт каждые двенадцать секунд «на всякий случай».
 */
@Schema(description = "Итог отчёта о связи")
public record PreflightMediaResponseDTO(

        @Schema(description = "Что сервер записал", example = "true", type = "boolean")
        boolean mediaOk,

        @Schema(description = "Серверное время приёма отчёта, миллисекунды эпохи",
                example = "1788600042000", type = "integer")
        long serverNowMs,

        @Schema(description = "Через сколько миллисекунд после приёма флаг протухнет и связь снова "
                + "будет считаться потерянной. Отчёт нужно повторять чаще этого срока",
                example = "25000", type = "integer")
        long mediaFlagTtlMs) {
}
