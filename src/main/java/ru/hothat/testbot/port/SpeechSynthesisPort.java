package ru.hothat.testbot.port;

/**
 * Синтез речи глазами области тест-ботов.
 *
 * <p>Единственный потребитель синтеза во всём продукте — «облако мыслей» бота,
 * поэтому порт живёт здесь, а не в общем месте: общего места на одного
 * потребителя не бывает.
 */
public interface SpeechSynthesisPort {

    /**
     * Озвучить короткую реплику.
     *
     * @param voiceId голос из закрытого набора; пусто — голос по умолчанию
     */
    Speech synthesize(String text, String voiceId);

    /**
     * Звук и то, чем он сделан.
     *
     * <p>Голос возвращается трижды и по-разному не случайно: {@code voiceId} —
     * то, что попросили (или дали взамен неизвестного), {@code label} — как
     * назвать голос человеку, {@code model} — что именно синтезировало фразу.
     * Последнее нужно техлогу игры, иначе по логу не понять, почему бот вдруг
     * зазвучал иначе.
     */
    record Speech(String mime, String audioBase64, String voiceId, String label, String model) {
    }
}
