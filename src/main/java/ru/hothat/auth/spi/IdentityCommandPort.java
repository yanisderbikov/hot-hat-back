package ru.hothat.auth.spi;

/**
 * Что соседи вправе попросить область {@code auth} изменить.
 *
 * <p>Ровно одно: отозвать доступ. Просит модерация — бан обязан гасить и
 * выданные access-токены, и живые refresh, иначе заблокированный вернётся в
 * игру через пятнадцать минут (§7.3, строка «Бан игрока»). Пишет при этом
 * по-прежнему владелец таблицы: сосед не трогает ни {@code token_version},
 * ни {@code refresh_token} — он лишь называет игрока и причину.
 *
 * <p>Командный порт, а не событие: это инвариант, а инварианты событиями не
 * выражаются никогда. Отзыв обязан лечь в ту же транзакцию, что и строка
 * блокировки.
 */
public interface IdentityCommandPort {

    /** Причины отзыва, которыми пользуются соседи. */
    String REASON_BAN = "ban";

    /**
     * Немедленно отозвать доступ игрока: поднять поколение токенов и погасить
     * живые refresh-токены. Идемпотентно по смыслу — повторный вызов просто
     * поднимает поколение ещё раз.
     */
    void revokeAccess(String uid, String reason);
}
