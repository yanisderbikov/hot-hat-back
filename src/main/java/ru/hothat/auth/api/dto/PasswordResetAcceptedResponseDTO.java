package ru.hothat.auth.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Заявка на восстановление принята.
 *
 * <p>Поле ровно одно, и оно постоянное. Это не небрежность, а условие задачи:
 * ответ обязан быть одинаковым для зарегистрированного и незнакомого адреса,
 * иначе форма восстановления превращается в проверялку «есть ли у вас такой
 * пользователь». Ни статус, ни размер тела различаться не должны, поэтому
 * сюда нельзя положить ни адрес, ни срок жизни ссылки, ни признак отправки.
 *
 * <p>Отсюда и код 202, а не 200: сервер обещает попробовать, а не сообщает,
 * что письмо ушло.
 */
@Schema(description = "Заявка на восстановление принята")
public record PasswordResetAcceptedResponseDTO(

        @Schema(description = "Заявка принята к обработке. Всегда true — по значению нельзя "
                + "узнать, зарегистрирован ли адрес", example = "true")
        boolean accepted) {
}
