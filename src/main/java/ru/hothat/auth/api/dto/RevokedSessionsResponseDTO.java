package ru.hothat.auth.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Итог выхода со всех устройств.
 *
 * <p>Числа погашенных сессий здесь нет намеренно: движок отзывает их одним
 * обновлением и количества не возвращает, а выдумать его — значит однажды
 * показать человеку «завершено 3 сессии», когда их было пять.
 *
 * <p>Зато названо то, чего клиент сам не знает: гасится и текущая сессия
 * тоже, причём немедленно. Выход со всех устройств поднимает поколение
 * токенов, поэтому выданный минуту назад access-токен перестаёт работать
 * сразу, а не доживает свои пятнадцать минут, — и клиенту надо не «забыть
 * токены когда-нибудь», а увести человека на экран входа прямо сейчас.
 */
@Schema(description = "Все сессии завершены")
public record RevokedSessionsResponseDTO(

        @Schema(description = "Завершена ли и текущая сессия тоже. Всегда true", example = "true")
        boolean currentSessionEnded,

        @Schema(description = "Момент отзыва по часам сервера, миллисекунды эпохи",
                example = "1788600000000", type = "integer")
        long revokedAtMs) {
}
