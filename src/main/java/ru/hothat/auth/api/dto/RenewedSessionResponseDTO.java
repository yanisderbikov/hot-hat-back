package ru.hothat.auth.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Обновлённая пара токенов.
 *
 * <p>Учётка приезжает и сюда, хотя запрос был только про токены. Причина в
 * том, что обновление — единственный регулярный разговор клиента с сервером
 * об этой сессии: за пятнадцать минут ник, отображаемое имя или права
 * администратора могли смениться с другого устройства, и обновление — самый
 * дешёвый момент их подхватить. Ходить за этим отдельным запросом раз в
 * четверть часа было бы вдвое дороже.
 *
 * <p>Прежний refresh-токен после этого ответа недействителен: пара
 * ротируется целиком.
 */
@Schema(description = "Обновлённая сессия")
public record RenewedSessionResponseDTO(

        @Schema(description = "Новая пара токенов; прежний refresh погашен")
        SessionTokensView tokens,

        @Schema(description = "Учётная запись владельца сессии на момент обновления")
        AccountView account) {
}
