package ru.hothat.auth.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Гость стал полноценным аккаунтом.
 *
 * <p>Ответ 200, а не 201: учётная запись существовала и до этого вызова —
 * поменялся её род, а вместе с ним и набор открытых адресов. Идентификатор
 * не меняется, поэтому весь прогресс — комнаты, друзья, рейтинг — остаётся
 * на месте.
 *
 * <p>Пара токенов новая: прежний access-токен нёс роль гостя, и оставить его
 * значило бы держать на руках ключ с меньшими правами, чем у учётки, до конца
 * его срока.
 */
@Schema(description = "Учётная запись после апгрейда")
public record UpgradedGuestAccountResponseDTO(

        @Schema(description = "Новая пара токенов: прежняя, гостевая, больше не нужна")
        SessionTokensView tokens,

        @Schema(description = "Та же учётная запись, теперь с почтой и родом user")
        AccountView account) {
}
