package ru.hothat.conference.port;

import java.util.List;
import java.util.Optional;

/**
 * Что область видео-чата требует от видеосвязи.
 *
 * <p>Порт, а не прямой вызов клиента LiveKit, — по той же причине, что у
 * {@code room.port.VideoSessionPort}: сценарий решает, <b>кого</b> пускать,
 * а как из этого получается подписанный токен и учётка ретранслятора —
 * предмет внешней системы. Реализация лежит в {@code store}: единственном
 * слое, которому позволено знать чужие протоколы.
 *
 * <p>У видео-чата все участники равны: каждый показывает себя и видит
 * остальных. Поэтому у участника здесь нет ни роли, ни признака «может
 * публиковать» — токен один на всех.
 */
public interface ConferenceVideoPort {

    /** Адрес сервера видеосвязи, который называют браузеру. */
    String serverUrl();

    /** Подписанный токен участника видео-чата. */
    String participantToken(String conferenceId, String identity, String name);

    /**
     * Короткоживущая учётка ретранслятора; пусто — ретранслятор не настроен.
     *
     * <p>Не ошибка: без него связь держится напрямую.
     */
    Optional<TurnTicket> turnTicket(String identity);

    /**
     * Кто сейчас действительно в звонке.
     *
     * <p>Спрашивают перед повторным приглашением: участник, который ушёл,
     * не выходя из видео-чата (закрыл вкладку), остаётся в составе, и
     * позвать его снова можно только убедившись, что в звонке его нет.
     * Видеоузел недоступен — пустой список: тогда повторное приглашение
     * отказывать нечем, и оно проходит.
     */
    List<String> liveIdentities(String conferenceId);

    /**
     * Отключить участника от звонка. Лучшее из возможного: видеоузел
     * недоступен — исключение из состава всё равно записано, и следующий
     * токен ему уже не выдадут.
     */
    void disconnect(String conferenceId, String identity);

    /** Учётка ретранслятора: адреса, имя, пароль и срок. */
    record TurnTicket(List<String> urls, String username, String credential, long ttlSeconds) {
    }
}
