package ru.hothat.admin.port;

/**
 * Видеокомната глазами консоли администратора.
 *
 * <p>Консоль умеет ровно две вещи: выставить человека и погасить комнату
 * целиком. Ни выдачи токенов, ни рассылки здесь нет и не будет — это работа
 * комнаты и партии, и повторять её у администратора значило бы завести вторую
 * формулу допуска к видеосвязи.
 *
 * <p>Порт нужен потому, что видеослужба — чужая инфраструктура: сценарий
 * не должен знать ни про twirp, ни про имя комнаты в LiveKit.
 */
public interface VideoRoomPort {

    /** Выставить участника из видеокомнаты; отсутствующий — не ошибка. */
    void evict(String roomId, String uid);

    /** Погасить видеокомнату вместе с закрытием игровой. */
    void close(String roomId);
}
