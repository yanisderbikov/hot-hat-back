package ru.hothat.admin.port;

import java.util.Optional;

/**
 * Файловое хранилище глазами консоли администратора.
 *
 * <p>Консоль спрашивает о хранилище две вещи и делает одну: настроено ли оно,
 * куда смотрит и — снести объект снятой записи. Подписанных ссылок здесь нет:
 * их выдаёт та область, которой файл принадлежит, и второй формулы подписи у
 * администратора быть не должно.
 *
 * <p>Ненастроенное хранилище — это ответ, а не ошибка: {@link #target()}
 * пуст, и сценарий сам решает, беда это или строка «не настроено» на экране.
 */
public interface ObjectStoragePort {

    /** Настроено ли хранилище: без ключей ни ссылку подписать, ни файл снести. */
    boolean configured();

    /** Куда сервис складывает файлы; пусто — хранилище не настроено. */
    Optional<Target> target();

    /**
     * Снести объект.
     *
     * @return {@code true} — команда ушла в хранилище; {@code false} — хранилище
     *         не настроено либо отказало. Исключения наружу не выходят: снос
     *         файла сопровождает решение администратора, а не отменяет его.
     */
    boolean delete(String objectPath);

    /** Бакет и адрес, которые консоль показывает администратору. */
    record Target(String provider, String bucket, String endpoint) {
    }
}
