package ru.hothat.admin.usecase;

/**
 * События, после которых кого-то надо выставить из видеокомнаты LiveKit.
 *
 * <p>Существуют ради одного правила §7.2: внешний вызов внутри транзакции
 * запрещён. Бан и закрытие комнаты пишут в базу и зовут LiveKit; пока это
 * делалось подряд в одном методе, ответ сети держал открытой транзакцию,
 * задевающую и учётку, и место игрока, а падение LiveKit было опасно тем, что
 * ловилось молча ({@code AdminServiceImpl:281-284, 313-316}) — то есть могло и
 * не пойматься.
 *
 * <p>Событиями здесь выражается только то, что вправе опоздать (§7.3): человек
 * уже забанен и его токены уже отозваны, отключение от видео — следствие, а не
 * инвариант.
 */
public final class AdminEvictionEvents {

    private AdminEvictionEvents() {
    }

    /** Игрок забанен и его надо выставить из видеокомнаты. */
    public record PlayerBanned(String roomId, String uid) {
    }

    /** Комната закрыта администратором — видеокомнату можно сносить. */
    public record RoomClosedByAdmin(String roomId) {
    }
}
