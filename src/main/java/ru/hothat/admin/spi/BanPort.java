package ru.hothat.admin.spi;

import java.util.Collection;
import java.util.Map;
import java.util.Optional;

/**
 * Что область {@code admin} отвечает соседям о блокировке.
 *
 * <p>Спрашивают её вход, обмен refresh-токена и разбор access-токена: пускать
 * заблокированного нельзя, а факт блокировки принадлежит модерации и живёт в
 * её таблице. Обратное направление — отзыв доступа при бане — идёт через
 * {@code auth.spi.IdentityCommandPort}.
 *
 * <p><b>Две области знают друг о друге, и это осознанно.</b> Разорвать пару
 * можно было бы, вернув в учётку булев флаг «забанен», — но именно три
 * несогласованных источника правды о бане (флаг, строка причины, поколение
 * токенов) и были той бедой, ради которой затевался переезд. Пусть лучше
 * ссылка идёт в обе стороны, но через объявленные порты, чем правда о бане
 * лежит в двух местах.
 */
public interface BanPort {

    /** Заблокирован ли игрок прямо сейчас. */
    boolean banned(String uid);

    /** Действующая блокировка; пусто — не заблокирован. */
    Optional<Ban> activeBan(String uid);

    /** Заблокированные из названных: дашборд спрашивает сразу про всех. */
    Map<String, Ban> activeBans(Collection<String> uids);

    /**
     * Блокировка в объёме, который нужен соседям.
     *
     * <p>Кто заблокировал — намеренно не отдаётся заблокированному: это имя
     * администратора, и знать его ему незачем. Поле есть, но за пределы
     * консоли не уходит: решает вызывающий, а не порт.
     */
    record Ban(String uid, String reason, String byUid, long bannedAtMs) {
    }
}
