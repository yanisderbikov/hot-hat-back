package ru.hothat.admin.spi;

import java.time.Instant;

/**
 * Что консоль администратора отвечает соседям о снимках расхода.
 *
 * <p>Спрашивает её ровно один сосед — область {@code machine}, где живёт агент
 * мониторинга. Агент снимает тот же снимок, что и кнопка «Проверить сейчас», но
 * с двумя отличиями: он уважает окно планового снятия и рассылает письма.
 * Порт объявлен у владельца таблиц, чтобы агенту не пришлось знать ни имён
 * восьми таблиц расхода, ни того, что письмо — это строка журнала.
 *
 * <p>Снимка наружу порт не отдаёт: агент его не рисует. Ему важно, что снято и
 * не пора ли будить дежурного, — отсюда три поля вместо четырёх уровней
 * вложенных карт.
 */
public interface UsageSnapshotPort {

    /**
     * Разрешён ли плановый запуск в текущий час.
     *
     * <p>Снимки берутся четыре раза в сутки; агент зовёт адрес чаще и сам не
     * знает расписания. Проверка живёт у владельца снимков потому, что окно —
     * это правило расхода, а не правило машинной поверхности.
     */
    boolean scheduledWindowAllowed();

    /** Снять плановый снимок: с письмами о превышении и ежедневным отчётом. */
    Taken takeScheduled();

    /** Что получилось: когда сняли, сколько тревог завели и ушёл ли отчёт. */
    record Taken(Instant collectedAt, int alertsRaised, boolean reportDelivered) {
    }
}
