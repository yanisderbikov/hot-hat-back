package ru.hothat.recording.spi;

/**
 * Файл записи глазами чужих областей.
 *
 * <p>Спрашивает отсюда один сосед — консоль администратора, которой ссылку
 * дают на ЛЮБУЮ запись: она разбирает жалобу, а не смотрит своё. Право уже
 * проверено у неё, здесь остаётся подпись.
 *
 * <p>Порт объявлен у владельца записей потому, что подпись — это правило
 * записи, а не консоли: срок ссылки, тип содержимого и имя файла в загрузках
 * названы один раз и здесь. Пока их считал прежний движок, у соседа стояла
 * вторая копия тех же трёх значений.
 */
public interface RecordingFilePort {

    /**
     * Подписать ссылки на просмотр и на скачивание.
     *
     * @param objectPath   путь объекта в бакете; пусто — файла ещё нет
     * @param downloadName имя файла в папке загрузок
     */
    PlaybackUrls presign(String objectPath, String downloadName);

    /** Подписанные ссылки и момент, до которого они живы. */
    record PlaybackUrls(String watchUrl, String downloadUrl, long expiresAtMs) {
    }
}
