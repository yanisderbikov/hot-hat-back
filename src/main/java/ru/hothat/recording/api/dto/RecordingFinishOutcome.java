package ru.hothat.recording.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Чем кончилась попытка завершить запись партии.
 *
 * <p>Как и у старта, у старого {@code recordings finish} было три формы ответа
 * и свободная строка {@code reason}. Набор здесь закрыт и назван.
 *
 * <p>Все четыре исхода — успех: адрес идемпотентен по замыслу. Его зовут из
 * трёх мест ({@code app-core.js:13000}, {@code :13025} и конец церемонии), и
 * каждое может позвать вторым — завершать уже завершённое обязано быть
 * безопасно, иначе уборка за сбойной партией сама становилась бы сбоем.
 */
@Schema(description = "Исход попытки завершить запись партии")
public enum RecordingFinishOutcome {

    /** Съёмка остановлена этим вызовом, файл собирается или уже собран. */
    FINISHED,

    /** Запись была завершена раньше: повторный вызов ничего не изменил. */
    ALREADY_FINISHED,

    /** Записи этой партии нет: старт не звали либо он не удался. */
    NOT_STARTED,

    /** Запись партий в этой комнате выключена — останавливать нечего. */
    RECORDING_DISABLED
}
