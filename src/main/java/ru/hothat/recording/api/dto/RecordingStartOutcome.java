package ru.hothat.recording.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Чем кончилась попытка начать запись партии.
 *
 * <p>Старый {@code recordings start} отвечал тремя несовместимыми объектами:
 * {@code {ok,skipped,reason}}, {@code {ok,started:false,recording}} и
 * {@code {ok,started:true,recordingId,egressId}}. Клиент различал их по набору
 * ключей, а {@code reason} был свободной строкой — то есть смысл ответа жил в
 * тексте, который никто не проверял (замечание C6 аудита). Здесь исход назван
 * словом из закрытого набора.
 *
 * <p>Отказом ни один из этих исходов не является: выключенная запись и
 * закрытая комната — это «снимать нечего», а не ошибка вызова. Поэтому они
 * попали в перечисление, а не в коды ошибок: клиент, который зовёт старт перед
 * каждой партией не глядя, не должен ловить исключение на штатном ходе дел.
 */
@Schema(description = "Исход попытки начать запись партии")
public enum RecordingStartOutcome {

    /** Задание Egress создано этим вызовом: рекордер поднимается. */
    STARTED,

    /**
     * Запись этой партии уже идёт. Так отвечает и повтор того же вызова, и
     * гонка двух вкладок: секундная блокировка старта не даёт создать второй
     * Egress на одну партию.
     */
    ALREADY_RUNNING,

    /** Запись партий в этой комнате выключена хозяином — снимать нечего. */
    RECORDING_DISABLED,

    /** Комната уже закрыта: начинать съёмку не для чего. */
    ROOM_CLOSED
}
