package ru.hothat.lobby.usecase;

/**
 * Пределы чтений лобби: сколько строк адрес забирает из хранилища за раз.
 *
 * <p>Держатся вместе, а не по use-case, потому что предел называет и ответ:
 * {@code limit} в теле обязан совпадать с тем, с чем ходили в базу, иначе
 * клиент не поймёт, полон ли список.
 */
public final class LobbyReadLimits {

    /**
     * Сколько комнат отдаём витрине по умолчанию.
     *
     * <p>Полсотни — с запасом: экран показывает все живые комнаты сразу, а их
     * в самый людный час единицы. Прежнего предела у этого списка не было
     * вовсе — подписка привозила все комнаты живых фаз.
     */
    public static final int ROOMS = 50;

    /**
     * Сколько комнат читаем из каждой живой фазы, прежде чем отбирать видимые.
     *
     * <p>Больше страницы намеренно: отбор идёт после чтения, и если читать
     * ровно {@code limit}, то полсотни приватных комнат подряд вытеснили бы из
     * ответа все публичные — список выглядел бы пустым при живых комнатах.
     * Запас в четыре страницы делает такой исход невероятным, а не невозможным:
     * невозможным его сделает запрос «фаза среди … и видима» с курсором, а он
     * появится вместе с новой схемой.
     */
    public static final int ROOMS_SCAN_PER_PHASE = 200;

    /**
     * Как часто подтверждать, что превью открыто.
     *
     * <p>Минута — тот же период, с которым стучится {@code live-preview.js:102}.
     * Он вчетверо меньше окна, за которое зритель считается ушедшим, так что
     * один потерянный удар сердца никого из комнаты не выкидывает.
     */
    public static final long PREVIEW_HEARTBEAT_MS = 60_000;

    private LobbyReadLimits() {
    }
}
