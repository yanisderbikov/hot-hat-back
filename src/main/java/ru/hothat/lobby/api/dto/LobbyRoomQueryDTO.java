package ru.hothat.lobby.api.dto;

import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;

/**
 * Отбор страницы витрины открытых комнат.
 *
 * <p>Ни отбора по дивизиону, ни поиска по названию здесь нет, и это решение.
 * Экран главной фильтрует список у себя ({@code home/home.js:74-77}) и делает
 * это не от бедности: рядом со списком он показывает общее число живых комнат
 * и каждые тридцать секунд крутит превью по всем ним. Сервер, отдавший уже
 * отобранный список, забрал бы у экрана и счётчик, и пул для ротации, а
 * добирать их вторым запросом — это два обращения вместо одного за тем же
 * самым.
 *
 * <p>Курсора нет по той же причине, что у друзей и мемов: движок за этим
 * адресом отдаёт первую и единственную страницу, и принимать значение,
 * которое некому выдать, — обман.
 */
@Schema(description = "Параметры страницы витрины комнат")
public record LobbyRoomQueryDTO(

        /**
         * Обёрточный тип, а не int: «не задано» и «задано числом» — разные
         * случаи, а единственное место умолчания живёт в use-case.
         */
        @Parameter(description = "Сколько комнат вернуть; по умолчанию 50", example = "50")
        @Min(value = 1, message = "Размер страницы должен быть положительным.")
        @Max(value = 200, message = "Больше двухсот комнат за раз не отдаём.")
        Integer limit) {
}
