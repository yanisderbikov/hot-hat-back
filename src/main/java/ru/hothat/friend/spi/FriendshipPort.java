package ru.hothat.friend.spi;

import java.util.List;

/**
 * Что область дружбы отвечает соседям.
 *
 * <p>Единственный вопрос, который задают снаружи: «эти двое друзья?». Его
 * задаёт переписка — писать другу можно, чужому нельзя, — и он же стоит в
 * плане read-портом {@code FriendshipPort}. Порт, а не общий репозиторий:
 * так соседняя область не получает доступ к таблицам дружбы и не начинает
 * писать в них мимо владельца.
 */
public interface FriendshipPort {

    /** Дружат ли эти двое; порядок сторон значения не имеет. */
    boolean areFriends(String uidA, String uidB);

    /**
     * Друзья игрока, новые сверху, не больше названного числа.
     *
     * <p>Нужен там, где сосед показывает друзей среди чужих строк: рейтинг
     * подсвечивает команды друзей. Отдаются идентификаторы, а не карточки:
     * имя и аватар — данные области профиля, и дружбе их пересказывать нечем.
     */
    List<String> friendUids(String uid, int limit);
}
