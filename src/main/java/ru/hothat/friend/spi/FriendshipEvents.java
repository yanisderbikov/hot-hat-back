package ru.hothat.friend.spi;

/**
 * О чём область дружбы извещает соседей.
 *
 * <p>Событие, а не прямой вызов: писать в чужие таблицы область дружбы не
 * вправе, а обратная зависимость ({@code friend} → {@code chat}) замкнула бы
 * кольцо — переписка уже спрашивает дружбу через {@link FriendshipPort}.
 */
public final class FriendshipEvents {

    private FriendshipEvents() {
    }

    /**
     * Двое перестали быть друзьями.
     *
     * <p>Слушателю полагается разобрать своё в той же транзакции, что и
     * разрыв: половинчатое состояние — связи уже нет, а её следы у соседа
     * ещё есть — это ровно та рассинхронизация, из-за которой у игрока
     * навсегда зависал значок непрочитанного.
     */
    public record Unlinked(String uidA, String uidB) {
    }
}
