package ru.hothat.config;

/**
 * Пользователь запроса: личность из нашего access-токена, права — из области
 * {@code auth}.
 *
 * <p>{@code guest} назван отдельным полем, а не выведен из пустой почты: род
 * учётки решает, какую роль выдать, а роль — единственное, что отделяет гостя
 * от игрока.
 *
 * <p><b>{@code name} здесь пуст, и это намеренно.</b> Имя игрока принадлежит
 * его карточке в области {@code profile} и меняется её сценариями; разбор
 * токена происходит на каждом запросе, и читать ради имени вторую таблицу
 * значило бы платить за него всегда, а нужно оно нескольким операциям.
 * Кому нужно — спрашивает {@code PlayerCardPort.nicknameOf(uid)}. Поле
 * оставлено в записи, чтобы не переписывать полтораста мест ради значения,
 * которое почти нигде не читают.
 */
public record HotHatUser(String uid, String email, String name, boolean admin, boolean owner, boolean guest) {

    public String emailLower() {
        return email == null ? "" : email.trim().toLowerCase();
    }
}
