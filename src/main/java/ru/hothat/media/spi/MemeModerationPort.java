package ru.hothat.media.spi;

/**
 * Что область {@code media} позволяет консоли администратора.
 *
 * <p>Отдельный порт от {@link MemeLibraryPort}, потому что права разные:
 * читать библиотеку вправе любой игрок, а снимать чужой мем и переписывать
 * его ролик — только администратор. Один порт с обоими наборами методов
 * означал бы, что партия технически способна снять мем.
 *
 * <p>Право проверяет вызывающий — сценарий области {@code admin}. Здесь
 * проверяются только правила самой библиотеки: встроенный мем защищён, а
 * несуществующий отвечает 404.
 */
public interface MemeModerationPort {

    /** Снять чужой мем: карточка становится надгробием, файлы уходят. */
    void withdraw(String memeId);

    /**
     * Сохранить сжатую для мобильных версию ролика.
     *
     * <p>Байты приезжают data-URL'ом от оптимизатора в браузере и уезжают в
     * хранилище под тем же ключом, что и прежний ролик. Раньше они оставались
     * текстом прямо в строке карточки, и чтение библиотеки тянуло эти
     * мегабайты в память на каждую карточку.
     */
    Optimized saveOptimized(String memeId, String videoDataUrl, String contentType,
                            Integer durationMs, String version);

    /**
     * Сверить библиотеку с бакетом: завести карточки по файлам, которые в
     * хранилище есть, а в базе их нет. Нужна после сбоев загрузки, когда файл
     * уже уехал, а метаданные записать не успели.
     */
    Reconciliation reconcile();

    /** Итог сохранения сжатой версии. */
    record Optimized(String memeId, int bytes, String contentType, int durationMs,
                     String version, long optimizedAtMs) {
    }

    /** Итог сверки: сколько роликов в бакете, сколько заведено, сколько уже было. */
    record Reconciliation(int videos, int recovered, int existing, int scannedObjects) {
    }
}
