package ru.hothat.media.spi;

import java.util.Collection;
import java.util.List;
import java.util.Optional;
import java.util.Set;

/**
 * Что область {@code media} отвечает соседям о библиотеке мемов.
 *
 * <p>Спрашивают её партия (диверсия «мем» показывает ролик) и консоль
 * администратора. Раньше обе читали таблицу сами через общий
 * {@code GetterMedia} и разбирали строку карточки на шесть полей про файл —
 * при том что нужны им ровно два: длительность ролика и его адрес.
 *
 * <p>Порт только читает. Права на мем, его владелец, размер файла и история
 * загрузок остаются в области медиа: диверсия не должна уметь их менять.
 */
public interface MemeLibraryPort {

    /** Мем, годный к показу; пусто — такого нет, он снят или ещё черновик. */
    Optional<PlayableMeme> find(String memeId);

    /**
     * Какие из этих мемов годятся к показу — одним чтением.
     *
     * <p>Обойма заряжается сразу пятью роликами, и спрашивать про каждый
     * отдельно значило бы пять чтений на один запрос. Возвращается не
     * «да/нет» на весь список, а найденное подмножество: вызывающему бывает
     * нужно назвать, чего именно не хватило.
     */
    Set<String> existing(Collection<String> memeIds);

    /**
     * Витрина библиотеки, свежие сверху, не больше предела.
     *
     * <p>Спрашивают её тест-боты: обойма бота заряжается из того же каталога,
     * что и у живого игрока, иначе в тестовой комнате нечем стрелять.
     * Черновики и снятые сюда не попадают — отбор делает выборка.
     */
    List<PlayableMeme> catalog(int limit);

    /**
     * Мем в объёме, который нужен сцене: сколько играть и что показывать.
     *
     * <p>Адрес и ключ названы оба. По адресу ролик играется прямо, а по ключу
     * берётся подписанная ссылка, которую браузер кеширует вместе с
     * range-запросами. Пусто у обоих — у мема нет файла в хранилище: такие
     * строки остались от прежней модели, где ролик лежал байтами в базе.
     */
    record PlayableMeme(String memeId, String title, int durationMs,
                        String videoUrl, String videoKey,
                        String posterUrl, String posterKey) {
    }
}
