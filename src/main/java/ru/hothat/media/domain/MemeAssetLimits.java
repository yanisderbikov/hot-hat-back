package ru.hothat.media.domain;

/**
 * Пределы, за которыми мем перестаёт быть мемом.
 *
 * <p>Те же числа стоят в переходном движке ({@code MediaServiceImpl:34-37}) и
 * остаются там вторым рубежом: билет выдаёт он, и отказать он обязан сам,
 * даже если однажды его позовут не отсюда. Здесь они объявлены затем, чтобы
 * запрос отвергался на входе, с человеческим текстом и указанием поля, а не
 * машинным кодом из середины сценария.
 *
 * <p>Предел ролика — восемь мегабайт, заставки — один: заставка едет вместе
 * с каждой карточкой библиотеки, а ролик грузится только когда его выпустили.
 */
public final class MemeAssetLimits {

    public static final long MAX_VIDEO_BYTES = 8L * 1024 * 1024;
    public static final long MAX_POSTER_BYTES = 1024L * 1024;

    /** Короче — щелчок вместо ролика; длиннее — диверсия перекрывает ход. */
    public static final int MIN_DURATION_MS = 100;
    public static final int MAX_DURATION_MS = 10000;

    private MemeAssetLimits() {
    }
}
